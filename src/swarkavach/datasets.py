def _find_transcript_file(root: Path) -> Optional[Path]:
    """Locate the transcript file without assuming the archive's layout."""
    names = ("text", "transcription.txt", "transcripts.txt", "text.txt")
    for n in names:
        hits = list(root.rglob(n))
        if hits:
            return hits[0]
    for p in root.rglob("*.txt"):
        if p.stat().st_size > 2000:
            return p
    return None


def _parse_transcripts(path: Path) -> Dict[str, str]:
    """Kaldi-style `utt_id transcript` lines, and a few common variants."""
    out: Dict[str, str] = {}
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return out
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        if "\t" in line:
            uid, _, rest = line.partition("\t")
        else:
            uid, _, rest = line.partition(" ")
        uid, rest = uid.strip(), rest.strip()
        if uid and rest:
            out[uid] = rest
    return out


def gramvaani_metadata() -> Dict[str, Dict[str, str]]:
    """Per-utterance speaker attributes from Metadata.tar.gz.

    Columns are Uttids, Accent, Age, Gender, Background, Sentiment, District,
    State, Other. This is genuinely useful beyond bookkeeping: the ethics
    write-up notes that error rates differ across speakers and accents and
    that the project had no data to check it. With these labels the voice
    branch can at least be reported per gender and per accent.
    """
    out: Dict[str, Dict[str, str]] = {}
    arc = RAW_DIR / "Metadata.tar.gz"
    if not arc.exists():
        return out
    try:
        with tarfile.open(arc, "r:gz") as tf:
            for m in tf.getmembers():
                if not m.name.endswith(".txt"):
                    continue
                fh = tf.extractfile(m)
                if fh is None:
                    continue
                lines = fh.read().decode("utf-8", errors="replace").splitlines()
                if not lines:
                    continue
                header = [h.strip() for h in lines[0].split("\t")]
                for line in lines[1:]:
                    parts = [p.strip() for p in line.split("\t")]
                    if len(parts) < 2:
                        continue
                    row = dict(zip(header[1:], parts[1:]))
                    out[parts[0]] = {k: v for k, v in row.items() if v and v != "NA"}
    except Exception:
        return out
    return out


def gramvaani_utterances(
    which: Sequence[str] = ("gramvaani_dev", "gramvaani_eval"),
    limit: Optional[int] = None,
    min_seconds: float = 1.5,
    max_seconds: float = 20.0,
    require_text: bool = False,
) -> List[Dict[str, Any]]:
    """Real human Hindi telephone utterances.

    Returns dicts with `path`, `utt_id`, `speaker`, `dataset`, `duration` and
    whatever speaker attributes the metadata carries. `text` is present only
    where a transcript exists.

    Note on transcripts: they live in an extensionless file named `text`
    inside each archive, Kaldi style, not in a `.txt`. Easy to miss when
    listing the tar by extension. Pass `require_text=True` to drop anything
    untranscribed.

    Note on speakers: ids look like `01-00003-01`. The middle field identifies
    the recording, so it is used as the speaker proxy. GramVaani is community
    radio, so one recording is usually one caller, but this is a proxy and the
    report should say so rather than claim true speaker labels.
    """
    import soundfile as sf

    meta = gramvaani_metadata()
    out: List[Dict[str, Any]] = []
    for name in which:
        root = extract(name)
        if root is None:
            continue
        tpath = _find_transcript_file(root)
        transcripts = _parse_transcripts(tpath) if tpath else {}

        for audio in sorted(root.rglob("*")):
            if audio.suffix.lower() not in AUDIO_EXT:
                continue
            uid = audio.stem
            text = transcripts.get(uid, "")
            if require_text and not text:
                continue
            try:
                info = sf.info(str(audio))
                dur = float(info.frames) / float(info.samplerate or 1)
            except Exception:
                continue
            if not (min_seconds <= dur <= max_seconds):
                continue
            parts = uid.split("-")
            speaker = "-".join(parts[:2]) if len(parts) >= 2 else uid
            rec = {
                "path": str(audio),
                "text": text,
                "utt_id": uid,
                "speaker": speaker,
                "dataset": name,
                "duration": round(dur, 3),
                "sample_rate": int(getattr(info, "samplerate", 0) or 0),
            }
            rec.update(meta.get(uid, {}))
            out.append(rec)
            if limit and len(out) >= limit:
                return out
    return out


