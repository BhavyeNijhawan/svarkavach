def robocall_transcripts(limit: Optional[int] = None) -> List[Dict[str, Any]]:
    """The robocall transcripts alone, without touching the audio.

    `robocall_calls` walks the whole clone to pair each row with its WAV, which
    means 1.7 GB has to be on disk. The out-of-domain intent test only needs
    the words, and metadata.csv is 684 KB, so this reads that file and stops.
    That is also what lets the fetch step skip the audio entirely.
    """
    root = RAW_DIR / DATASETS["robocall"]["dir"]
    meta = root / "metadata.csv"
    if not meta.exists():
        found = next(root.rglob("metadata.csv"), None) if root.exists() else None
        if found is None:
            return []
        meta = found

    out: List[Dict[str, Any]] = []
    with open(meta, newline="", encoding="utf-8", errors="replace") as fh:
        for r in csv.DictReader(fh):
            text = (r.get("transcript") or "").strip()
            # a handful of rows are empty or a single word of hold music
            if len(text.split()) < 4:
                continue
            out.append({
                "id": Path((r.get("file_name") or "").strip()).stem or f"rc{len(out)}",
                "transcript": text,
                "language": (r.get("language") or "en").strip(),
                "case": (r.get("case_details") or "").strip(),
            })
            if limit and len(out) >= limit:
                break
    return out


def robocall_calls(limit: Optional[int] = None) -> List[Dict[str, Any]]:
    """Real illegal robocalls with their transcripts.

    These are English, and they are recordings rather than two-party
    conversations, so they do not slot into the Hinglish four-cell grid. What
    they are good for is a genuine out-of-domain test of the intent branch:
    the scripts are real fraud, written by real fraudsters, and nothing in
    this project was tuned on them.
    """
    root = RAW_DIR / DATASETS["robocall"]["dir"]
    if not root.exists():
        return []

    meta = None
    for cand in root.rglob("metadata.csv"):
        meta = cand
        break
    rows: List[Dict[str, Any]] = []
    if meta is not None:
        with open(meta, newline="", encoding="utf-8", errors="replace") as fh:
            for r in csv.DictReader(fh):
                rows.append({k.strip(): (v or "").strip() for k, v in r.items()})

    audio_by_stem: Dict[str, Path] = {}
    for p in root.rglob("*"):
        if p.suffix.lower() in AUDIO_EXT:
            audio_by_stem[p.stem] = p

    out: List[Dict[str, Any]] = []
    for r in rows:
        stem = None
        for key in ("id", "file", "filename", "audio", "call_id", "name"):
            v = r.get(key)
            if v:
                stem = Path(v).stem
                break
        if stem is None or stem not in audio_by_stem:
            continue
        text = ""
        for key in ("transcript", "transcription", "text", "content"):
            if r.get(key):
                text = r[key]
                break
        out.append({
            "path": str(audio_by_stem[stem]),
            "text": text,
            "call_id": stem,
            "dataset": "robocall",
            "meta": r,
        })
        if limit and len(out) >= limit:
            break

    # metadata missing or unparseable: fall back to the audio files alone
    if not out:
        for stem, p in sorted(audio_by_stem.items()):
            out.append({"path": str(p), "text": "", "call_id": stem,
                        "dataset": "robocall", "meta": {}})
            if limit and len(out) >= limit:
                break
    return out


