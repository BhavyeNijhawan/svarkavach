"""Real, publicly downloadable corpora, and what each one is honestly for.

The generated corpus in `corpus/` gives paired audio and transcripts, which is
what the fusion grid and the live demo need. What it cannot give is a real
human voice, because every sample in it is machine generated. These datasets
fill that gap.

| dataset | what it is | what it is used for here |
|---|---|---|
| GramVaani (OpenSLR 118) | spontaneous Hindi TELEPHONE speech, real speakers | the bonafide side of the voice branch |
| NCSU WSPR robocalls | 1,432 genuine scam robocalls with transcripts | a real-world test set for the intent branch |

The important design point is how the anti-spoofing set is built. GramVaani
ships transcripts, so the spoof side is generated by rendering the SAME
transcript with a neural voice. That is the construction ASVspoof uses: the
two classes say the same words, so a detector cannot cheat by keying on
content instead of on voice. As far as the dataset survey found, no Hindi
anti-spoofing set exists at all, so this pairing is built here rather than
downloaded.

Licences, because a report has to state them. GramVaani is free for academic
use, with commercial use needing permission from contact@gramvaani.org. The
NCSU robocall audio is US federal government evidence and is public domain;
its documentation is CC BY-ND. Neither needs an account or an approval form.
"""

