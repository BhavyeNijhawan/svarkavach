def status() -> Dict[str, Dict[str, Any]]:
    """What is on disk right now."""
    out: Dict[str, Dict[str, Any]] = {}
    for name, spec in DATASETS.items():
        if "archive" in spec:
            p = RAW_DIR / spec["archive"]
            extracted = RAW_DIR / spec["archive"].replace(".tar.gz", "")
            out[name] = {
                "archive": p.exists(),
                "archive_mb": round(p.stat().st_size / 1e6, 1) if p.exists() else 0,
                "extracted": extracted.exists(),
                "path": str(extracted if extracted.exists() else p),
            }
        else:
            d = RAW_DIR / spec["dir"]
            out[name] = {"cloned": d.exists(), "path": str(d)}
    return out


def extract(name: str, force: bool = False) -> Optional[Path]:
    """Extract a downloaded archive, returning the directory it landed in."""
    spec = DATASETS.get(name)
    if not spec or "archive" not in spec:
        return None
    archive = RAW_DIR / spec["archive"]
    if not archive.exists():
        return None
    dest = RAW_DIR / spec["archive"].replace(".tar.gz", "")
    if dest.exists() and not force:
        return dest
    dest.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive, "r:gz") as tf:
        # filter="data" refuses absolute paths and traversal, which matters for
        # any archive you did not build yourself
        try:
            tf.extractall(dest, filter="data")
        except TypeError:            # Python without the filter argument
            tf.extractall(dest)
    return dest


