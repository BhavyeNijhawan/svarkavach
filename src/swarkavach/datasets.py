def noise_floor_db(x, sr: int = TARGET_SR) -> float:
    """Level of the quietest tenth of frames, in dB. A channel fingerprint."""
    import numpy as np

    from .dsp.framing import frame_signal, short_time_energy

    x = np.asarray(x, dtype=np.float64).ravel()
    if x.size < 2000:
        return -90.0
    fr = frame_signal(x, 200, 80, window="hamming")
    e = short_time_energy(fr)
    db = 10.0 * np.log10(np.maximum(e, 1e-12))
    return float(np.percentile(db, 10))


def match_channel(bonafide, spoof, sr: int = TARGET_SR, seed: int = 0,
                  codec: str = "g711u"):
    """Put both sides of a pair through the same channel.

    This is the single most important step in building a spoofing set, and
    getting it wrong silently ruins the whole evaluation. Real GramVaani audio
    is a phone recording with room tone and line hiss sitting around -41 dB.
    A synthesiser writes digital silence at about -88 dB. Measured on this
    data, the noise floor ALONE separated the two classes at AUC 0.970, so a
    detector trained on the raw pairing would score beautifully while having
    learned nothing except "quiet means fake".

    So: both sides get the same codec, and the spoof gets shaped noise added
    until its floor matches its own partner's. After that the systematic
    difference left between the two is the voice, which is the thing the
    branch is supposed to be reading.
    """
    import numpy as np

    from .channel import add_noise, apply_codec

    rng = np.random.default_rng(seed)
    b = np.asarray(bonafide, dtype=np.float32).ravel()
    s = np.asarray(spoof, dtype=np.float32).ravel()

    try:
        b, _ = apply_codec(b, sr, codec)
        s, _ = apply_codec(s, sr, codec)
    except Exception:
        pass

    # Fix the gain FIRST, and to the same peak on both sides. Matching floors
    # and then letting the writer peak-normalise afterwards undoes the whole
    # thing: real speech has a higher crest factor than synthesised speech, so
    # scaling both to a common peak moves their floors by different amounts.
    # That is exactly what happened on the first attempt, and the floors came
    # out 38 dB apart despite the matching code running correctly. Callers
    # must write these with peak=None.
    def _to_peak(x, peak=0.95):
        m = float(np.max(np.abs(x))) if x.size else 0.0
        return (x * (peak / m)).astype(np.float32) if m > 1e-9 else x.astype(np.float32)

    b = _to_peak(b)
    s = _to_peak(s)

    target = noise_floor_db(b, sr)
    current = noise_floor_db(s, sr)

    if target - current > 3.0:
        # Work out the noise scale by measuring rather than by converting
        # between an SNR and a percentile-of-frame-energy. Those are different
        # units (short_time_energy sums over the frame, so there is a
        # 10*log10(frame_len) offset lurking), and getting the conversion
        # wrong overshot the target by about 18 dB, leaving the SPOOF noisier
        # than the real recording.
        #
        # noise_floor_db is scale equivariant: multiplying a signal by k moves
        # its floor by 20*log10(k). So measure the floor of unit-scale noise
        # once, then solve for k exactly.
        n = rng.normal(0.0, 1.0, s.size).astype(np.float32)
        f_unit = noise_floor_db(n, sr)
        k = 10.0 ** ((target - f_unit) / 20.0)
        s = (s + n * k).astype(np.float32)

    return b.astype(np.float32), np.asarray(s, dtype=np.float32)


def _write_pair(u, spoof, i, sr, out_dir, rng, manifest) -> bool:
    """Write one bonafide and its matched spoof. Returns whether it landed."""
    from .audioio import read_audio, write_wav
    from .corpus import neural_tts as N

    if spoof is None:
        return False
    try:
        human, _ = read_audio(u["path"], sr=sr)
    except Exception:
        return False
    if human.size < int(0.5 * sr):
        return False

    # half plain TTS, half vocoded, so the spoof side is not one system
    vocoded = bool(rng.random() < 0.5)
    y = N.vocoder_artifacts(spoof, sr) if vocoded else spoof

    # Both sides through the same channel, and the spoof's noise floor matched
    # to its own partner's. Without this the pair is separable on silence level
    # alone at AUC 0.97 and the branch learns nothing about voice.
    human, y = match_channel(human, y, sr, seed=i)

    hp = out_dir / "bonafide" / f"{u['utt_id']}.wav"
    write_wav(hp, human, sr, peak=None)   # peak=None: see match_channel
    manifest.append({"path": str(hp), "label": 0, "kind": "bonafide",
                     "speaker": u["speaker"], "text": u["text"],
                     "source": u["dataset"]})

    sp = out_dir / "spoof" / f"{u['utt_id']}_{'voc' if vocoded else 'tts'}.wav"
    write_wav(sp, y, sr, peak=None)
    manifest.append({"path": str(sp), "label": 1,
                     "kind": "vocoded_tts" if vocoded else "tts",
                     "speaker": u["speaker"], "text": u["text"],
                     "source": "edge_tts"})
    return True


def build_antispoof_pairs(
    n: int = 300,
    sr: int = TARGET_SR,
    out_dir: Optional[Path] = None,
    seed: int = 0,
    progress: bool = True,
) -> Dict[str, Any]:
    """Pair real human Hindi speech with a spoof of the SAME transcript.

    This is the ASVspoof construction. For each real GramVaani utterance, the
    transcript is rendered with a neural voice, and half of those renderings
    additionally go through the LPC vocoder so the spoof side covers both
    plain text-to-speech and vocoder-based cloning.

    Because both classes say the same words, a detector cannot separate them
    on content, which is the whole point. Returns a manifest; the audio is
    written under `out_dir`.
    """
    import numpy as np

    from .audioio import read_audio, write_wav
    from .corpus import neural_tts as N

    out_dir = Path(out_dir or (RAW_DIR / "antispoof_pairs"))
    (out_dir / "bonafide").mkdir(parents=True, exist_ok=True)
    (out_dir / "spoof").mkdir(parents=True, exist_ok=True)

    utts = [
        u for u in gramvaani_utterances(limit=n * 3, require_text=True)
        # after stripping the markers there has to be enough text left that the
        # rendered clip is comparable in length to the real one
        if len(N.clean_for_tts(u["text"])) >= 25
    ][:n]
    if not utts:
        return {"error": "no GramVaani utterances found, is it downloaded?",
                "status": status()}

    rng = np.random.default_rng(seed)
    manifest: List[Dict[str, Any]] = []
    n_ok = 0

    # Render and write in chunks rather than holding every clip in memory at
    # once. Five hundred utterances of decoded audio plus their renders is well
    # over a gigabyte, and this machine has 8 GB total, so the all-at-once
    # version got killed by the OOM reaper part way through.
    CHUNK = 40
    for start in range(0, len(utts), CHUNK):
        batch = utts[start:start + CHUNK]
        items = []
        for j, u in enumerate(batch):
            v = N.voice_for_speaker(f"spoof_{(start + j) % 40}", seed)
            # GramVaani transcripts are already Devanagari, so no
            # transliteration. They do carry <inaudible> markers though, and
            # the TTS service reads those as SSML tags and stops rendering at
            # the first one, so they have to be stripped.
            items.append((N.clean_for_tts(u["text"]), v["voice"], v["rate"], v["pitch"]))

        rendered = N.synth_batch(items, sr=sr)
        if progress:
            got = sum(1 for r in rendered if r is not None)
            print(f"    {start + len(batch)}/{len(utts)} rendered "
                  f"({got}/{len(batch)} in this chunk)", flush=True)

        for j, (u, spoof) in enumerate(zip(batch, rendered)):
            i = start + j
            if _write_pair(u, spoof, i, sr, out_dir, rng, manifest):
                n_ok += 1
        del rendered


    # Audit before writing, so a leaky set announces itself rather than being
    # discovered three experiments later.
    audit = confound_audit(manifest, sr)
    if progress:
        print(f"  channel audit: worst statistic AUC {audit.get('worst_auc')} "
              f"({audit.get('status')})")

    mpath = out_dir / "manifest.json"
    payload = {
        "confound_audit": audit,
        "n_pairs": n_ok,
        "n_files": len(manifest),
        "sample_rate": sr,
        "bonafide_source": "GramVaani (OpenSLR 118), real Hindi telephone speech",
        "spoof_source": "edge-tts neural voices, half through an LPC vocoder",
        "construction": "paired: each spoof renders the same transcript as its bonafide",
        "channel_matched": True,
        "channel_note": ("both sides through the same codec, spoof noise floor "
                         "matched to its partner; raw pairing leaked at AUC 0.97 "
                         "on noise floor alone"),
        "items": manifest,
    }
    mpath.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    payload["manifest"] = str(mpath)
    return payload


def confound_audit(manifest_items: Sequence[Dict[str, Any]],
                   sr: int = TARGET_SR) -> Dict[str, Any]:
    """Can a trivial channel statistic separate bonafide from spoof?

    This runs on every build and the result is stored in the manifest, because
    the failure it guards against is silent. A spoofing set whose two classes
    differ in noise floor gives a detector an easy shortcut, and the resulting
    equal error rate looks excellent while measuring the recording conditions
    rather than the speaker. Before channel matching, the noise floor alone
    scored AUC 0.970 on this data.

    Anything above about 0.75 means the set is not usable as it stands.
    """
    import numpy as np

    from .audioio import read_audio
    from .dsp.framing import frame_signal, short_time_energy, zero_crossing_rate
    from .evaluate import roc_auc

    rows: Dict[int, List[Dict[str, float]]] = {0: [], 1: []}
    for it in manifest_items:
        try:
            x, _ = read_audio(it["path"], sr=sr)
        except Exception:
            continue
        if x.size < 4000:
            continue
        fr = frame_signal(x, 200, 80, window="hamming")
        e = short_time_energy(fr)
        db = 10.0 * np.log10(np.maximum(e, 1e-12))
        rows[int(it["label"])].append({
            "noise_floor_db": float(np.percentile(db, 10)),
            "snr_proxy_db": float(np.percentile(db, 95) - np.percentile(db, 10)),
            "zcr_mean": float(np.mean(zero_crossing_rate(fr))),
            "duration": float(x.size) / sr,
        })

    out: Dict[str, Any] = {"per_statistic": {}, "n_bonafide": len(rows[0]),
                           "n_spoof": len(rows[1])}
    if not rows[0] or not rows[1]:
        out["status"] = "not enough audio to audit"
        return out

    worst = 0.5
    for k in ("noise_floor_db", "snr_proxy_db", "zcr_mean", "duration"):
        a = np.array([r[k] for r in rows[0]])
        b = np.array([r[k] for r in rows[1]])
        y = np.array([0] * a.size + [1] * b.size)
        auc = roc_auc(np.concatenate([a, b]), y)
        auc = max(auc, 1.0 - auc)      # leakage regardless of direction
        worst = max(worst, auc)
        out["per_statistic"][k] = {
            "bonafide_mean": round(float(a.mean()), 3),
            "spoof_mean": round(float(b.mean()), 3),
            "auc_alone": round(float(auc), 4),
        }
    out["worst_auc"] = round(float(worst), 4)
    out["status"] = ("channel leak, do not trust the EER" if worst > 0.75
                     else "weak residual leak" if worst > 0.62
                     else "clean")
    return out


def load_antispoof_pairs(out_dir: Optional[Path] = None) -> Dict[str, Any]:
    p = Path(out_dir or (RAW_DIR / "antispoof_pairs")) / "manifest.json"
    if not p.exists():
        return {}
    return json.loads(p.read_text(encoding="utf-8"))


def antispoof_pairs_as_calls(
    out_dir: Optional[Path] = None,
    split_ratio: float = 0.75,
    seed: int = 0,
) -> List[Any]:
    """The paired set wrapped as Call objects, so the scorer can train on it.

    `AntiSpoofScorer.fit` takes Calls carrying `audio_path` and `label_voice`.
    These are not conversations, they are single utterances, so the transcript
    is a placeholder and only the audio and the voice label mean anything.

    The split is speaker disjoint on the bonafide side: a spoof inherits the
    split of the real utterance whose transcript it renders, so a transcript
    never appears on both sides of the boundary. Getting that wrong would let
    the detector memorise content.
    """
    import random

    from .schema import Call, Turn

    man = load_antispoof_pairs(out_dir)
    items = man.get("items") or []
    if not items:
        return []

    speakers = sorted({it.get("speaker", "?") for it in items})
    rng = random.Random(seed)
    rng.shuffle(speakers)
    n_train = int(len(speakers) * split_ratio)
    split_of = {s: ("train" if i < n_train else "dev")
                for i, s in enumerate(speakers)}

    calls: List[Any] = []
    for i, it in enumerate(items):
        if not Path(it["path"]).exists():
            continue
        spk = it.get("speaker", f"pair_{i}")
        calls.append(Call(
            call_id=f"as_{Path(it['path']).stem}",
            turns=[Turn(index=0, speaker="caller",
                        text=(it.get("text") or "utterance")[:400])],
            label_scam=0,
            label_voice="synthetic" if int(it.get("label", 0)) == 1 else "human",
            scenario="antispoof_pair",
            speaker_id=spk,
            split=split_of.get(spk, "train"),
            audio_path=it["path"],
            sample_rate=int(man.get("sample_rate", TARGET_SR)),
            audio_source=it.get("source", "unknown"),
            meta={"kind": it.get("kind", "")},
        ))
    return calls


