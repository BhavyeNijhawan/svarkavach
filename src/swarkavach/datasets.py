def noise_floor_db(x, sr: int = TARGET_SR) -> float:
    """Level of the quietest tenth of frames, in dB. A channel fingerprint."""
    import numpy as np

    from .dsp.framing import frame_signal, short_time_energy

    x = np.asarray(x, dtype=np.float64).ravel()
    if x.size < 2000:
        return -90.0
    fr = frame_signal(x, 200, 80, window="hamming")
    e = short_time_energy(fr)
    db = 10.0 * np.log10(np.maximum(e, 1e-12))
    return float(np.percentile(db, 10))


def _quiet_spectrum(x, sr: int, n_fft: int = 256):
    """Average magnitude spectrum of the quietest frames, unit mean gain.

    This is the colour of the recording's own noise: line hiss, room tone and
    whatever the codec left behind. It is not flat, and that matters, see
    `match_channel`.
    """
    import numpy as np

    from .dsp.framing import frame_signal, short_time_energy

    hop = n_fft // 2
    if x.size < n_fft * 4:
        return None
    fr = frame_signal(x, n_fft, hop, window="hamming")
    if fr.shape[0] < 8:
        return None
    e = short_time_energy(fr)
    k = max(4, int(0.15 * fr.shape[0]))
    quiet = fr[np.argsort(e)[:k]]
    mag = np.abs(np.fft.rfft(quiet, n=n_fft, axis=-1)).mean(axis=0)
    m = float(mag.mean())
    return (mag / m) if m > 1e-12 else None


def _shaped_noise(n_samples: int, template, rng, n_fft: int = 256):
    """White noise recoloured to a magnitude template."""
    import numpy as np

    n = rng.normal(0.0, 1.0, n_samples).astype(np.float64)
    if template is None or n_samples < 8:
        return n.astype(np.float32)
    N = np.fft.rfft(n)
    shape = np.interp(np.linspace(0.0, 1.0, N.size),
                      np.linspace(0.0, 1.0, template.size), template)
    y = np.fft.irfft(N * shape, n=n_samples)
    sd = float(np.std(y))
    return (y / sd).astype(np.float32) if sd > 1e-12 else n.astype(np.float32)


def match_channel(bonafide, spoof, sr: int = TARGET_SR, seed: int = 0,
                  codec: str = "g711u"):
    """Put both sides of a pair through the same channel.

    This is the single most important step in building a spoofing set, and
    getting it wrong silently ruins the whole evaluation. Real GramVaani audio
    is a phone recording with room tone and line hiss sitting around -41 dB.
    A synthesiser writes digital silence at about -88 dB. Measured on this
    data, the noise floor ALONE separated the two classes at AUC 0.970, so a
    detector trained on the raw pairing would score beautifully while having
    learned nothing except "quiet means fake".

    So: both sides get the same codec, and the spoof gets shaped noise added
    until its floor matches its own partner's. After that the systematic
    difference left between the two is the voice, which is the thing the
    branch is supposed to be reading.
    """
    import numpy as np

    from .channel import add_noise, apply_codec

    rng = np.random.default_rng(seed)
    b = np.asarray(bonafide, dtype=np.float32).ravel()
    s = np.asarray(spoof, dtype=np.float32).ravel()

    try:
        b, _ = apply_codec(b, sr, codec)
        s, _ = apply_codec(s, sr, codec)
    except Exception:
        pass

    # Put both sides down the same phone line before anything is measured.
    #
    # A real phone call is band-limited and carries no DC, and the two sides
    # of this set arrive band-limited differently: the recordings are 8 kHz
    # telephone MP3 whose encoder stops just under 3 kHz, the renders are
    # 24 kHz resampled, and the vocoded half carries a DC offset from its
    # unipolar excitation. Matching the noise floor without doing this
    # matched it over a band the two sides did not share, so the floors came
    # out equal full-band and 4 dB apart inside the band the detector reads.
    from .antispoof.features import (BAND_HIGH_HZ, BAND_LOW_HZ, _brick_wall,
                                     trim_silence)

    b = _brick_wall(b - float(np.mean(b)), sr, BAND_LOW_HZ, BAND_HIGH_HZ)
    s = _brick_wall(s - float(np.mean(s)), sr, BAND_LOW_HZ, BAND_HIGH_HZ)

    # Trim here, before the floors are measured, and not only at feature time.
    #
    # A render begins and ends in silence; a field recording begins and ends
    # in room tone. Trimming at feature time therefore took the quietest
    # frames off the spoof and almost nothing off the recording, which lifted
    # the spoof's measured floor by 6 dB after the two had been matched to
    # within 1 dB. The match has to be made on the same signal the detector
    # is going to see.
    b = trim_silence(b, sr)
    s = trim_silence(s, sr)

    # Fix the gain FIRST, and to the same peak on both sides. Matching floors
    # and then letting the writer peak-normalise afterwards undoes the whole
    # thing: real speech has a higher crest factor than synthesised speech, so
    # scaling both to a common peak moves their floors by different amounts.
    # That is exactly what happened on the first attempt, and the floors came
    # out 38 dB apart despite the matching code running correctly. Callers
    # must write these with peak=None.
    def _to_peak(x, peak=0.95):
        m = float(np.max(np.abs(x))) if x.size else 0.0
        return (x * (peak / m)).astype(np.float32) if m > 1e-9 else x.astype(np.float32)

    b = _to_peak(b)
    s = _to_peak(s)

    floor_b = noise_floor_db(b, sr)
    floor_s = noise_floor_db(s, sr)

    # Lift BOTH sides to a common floor, not just the spoof.
    #
    # The old code added noise to the spoof when the recording was noisier,
    # and did nothing otherwise. Half the spoofs are put through
    # `vocoder_artifacts` first, which drives an LPC filter with a noise
    # excitation and leaves them NOISIER than the recording, so for that half
    # the branch never fired and the pair went out unmatched. Across 600
    # pairs the spoof floor came out 7 dB above the bonafide floor, and the
    # audit read 0.71 on noise floor and 0.81 on dynamic range.
    #
    # Noise cannot be taken out of a signal, so the match has to go the other
    # way: pick the louder of the two floors and bring the quieter side up to
    # it. Both lifts use the RECORDING's quiet spectrum, so the two classes
    # end with the same noise level and the same noise colour.
    #
    # The scale is solved in power, not by setting the added noise's own
    # floor to the target: a signal already near the target plus noise at the
    # target lands about 3 dB above it.
    shape = _quiet_spectrum(b, sr)
    target = max(floor_b, floor_s) + 1.0

    def lift(x, current_db):
        deficit_p = 10.0 ** (target / 10.0) - 10.0 ** (current_db / 10.0)
        if deficit_p <= 0.0 or shape is None:
            return np.asarray(x, dtype=np.float32)
        n = _shaped_noise(x.size, shape, rng)
        f_unit = noise_floor_db(n, sr)
        if not np.isfinite(f_unit):
            return np.asarray(x, dtype=np.float32)
        k = 10.0 ** ((10.0 * np.log10(deficit_p) - f_unit) / 20.0)
        return (x + n * k).astype(np.float32)

    return lift(b, floor_b), lift(s, floor_s)


def _write_pair(u, spoof, i, sr, out_dir, rng, manifest) -> bool:
    """Write one bonafide and its matched spoof. Returns whether it landed."""
    from .audioio import read_audio, write_wav
    from .corpus import neural_tts as N

    if spoof is None:
        return False
    try:
        human, _ = read_audio(u["path"], sr=sr)
    except Exception:
        return False
    if human.size < int(0.5 * sr):
        return False

    # half plain TTS, half vocoded, so the spoof side is not one system
    vocoded = bool(rng.random() < 0.5)
    y = N.vocoder_artifacts(spoof, sr) if vocoded else spoof

    # Both sides through the same channel, and the spoof's noise floor matched
    # to its own partner's. Without this the pair is separable on silence level
    # alone at AUC 0.97 and the branch learns nothing about voice.
    human, y = match_channel(human, y, sr, seed=i)

    hp = out_dir / "bonafide" / f"{u['utt_id']}.wav"
    write_wav(hp, human, sr, peak=None)   # peak=None: see match_channel
    manifest.append({"path": str(hp), "label": 0, "kind": "bonafide",
                     "speaker": u["speaker"], "text": u["text"],
                     "source": u["dataset"]})

    sp = out_dir / "spoof" / f"{u['utt_id']}_{'voc' if vocoded else 'tts'}.wav"
    write_wav(sp, y, sr, peak=None)
    manifest.append({"path": str(sp), "label": 1,
                     "kind": "vocoded_tts" if vocoded else "tts",
                     "speaker": u["speaker"], "text": u["text"],
                     "source": "edge_tts"})
    return True


def build_antispoof_pairs(
    n: int = 300,
    sr: int = TARGET_SR,
    out_dir: Optional[Path] = None,
    seed: int = 0,
    progress: bool = True,
) -> Dict[str, Any]:
    """Pair real human Hindi speech with a spoof of the SAME transcript.

    This is the ASVspoof construction. For each real GramVaani utterance, the
    transcript is rendered with a neural voice, and half of those renderings
    additionally go through the LPC vocoder so the spoof side covers both
    plain text-to-speech and vocoder-based cloning.

    Because both classes say the same words, a detector cannot separate them
    on content, which is the whole point. Returns a manifest; the audio is
    written under `out_dir`.
    """
    import numpy as np

    from .audioio import read_audio, write_wav
    from .corpus import neural_tts as N

    out_dir = Path(out_dir or (RAW_DIR / "antispoof_pairs"))
    (out_dir / "bonafide").mkdir(parents=True, exist_ok=True)
    (out_dir / "spoof").mkdir(parents=True, exist_ok=True)

    utts = [
        u for u in gramvaani_utterances(limit=n * 3, require_text=True)
        # after stripping the markers there has to be enough text left that the
        # rendered clip is comparable in length to the real one
        if len(N.clean_for_tts(u["text"])) >= 25
    ][:n]
    if not utts:
        return {"error": "no GramVaani utterances found, is it downloaded?",
                "status": status()}

    rng = np.random.default_rng(seed)
    manifest: List[Dict[str, Any]] = []
    n_ok = 0

    # Render and write in chunks rather than holding every clip in memory at
    # once. Five hundred utterances of decoded audio plus their renders is well
    # over a gigabyte, and this machine has 8 GB total, so the all-at-once
    # version got killed by the OOM reaper part way through.
    CHUNK = 40
    for start in range(0, len(utts), CHUNK):
        batch = utts[start:start + CHUNK]
        items = []
        for j, u in enumerate(batch):
            v = N.voice_for_speaker(f"spoof_{(start + j) % 40}", seed, script="deva")
            # GramVaani transcripts are already Devanagari, so no
            # transliteration. They do carry <inaudible> markers though, and
            # the TTS service reads those as SSML tags and stops rendering at
            # the first one, so they have to be stripped.
            items.append((N.clean_for_tts(u["text"]), v["voice"], v["rate"], v["pitch"]))

        rendered = N.synth_batch(items, sr=sr)
        if progress:
            got = sum(1 for r in rendered if r is not None)
            print(f"    {start + len(batch)}/{len(utts)} rendered "
                  f"({got}/{len(batch)} in this chunk)", flush=True)

        for j, (u, spoof) in enumerate(zip(batch, rendered)):
            i = start + j
            if _write_pair(u, spoof, i, sr, out_dir, rng, manifest):
                n_ok += 1
        del rendered

    # Say how many renders failed. This count used to be kept and never
    # printed, which is how a build that lost 389 of 600 lines passed as a
    # 211-pair set for a week.
    failed = len(utts) - n_ok
    if progress or failed:
        print(f"  rendered {n_ok} of {len(utts)} lines"
              + (f", {failed} FAILED (empty audio from the speech service)" if failed else ""),
              flush=True)
    if failed > len(utts) // 4:
        print("  more than a quarter of the lines failed. The set is usable but "
              "small; check the failure log before trusting it.", flush=True)


    # Audit before writing, so a leaky set announces itself rather than being
    # discovered three experiments later.
    audit = confound_audit(manifest, sr)
    if progress:
        print(f"  channel audit: worst statistic AUC {audit.get('worst_auc')} "
              f"({audit.get('status')})")

    mpath = out_dir / "manifest.json"
    payload = {
        "confound_audit": audit,
        "pairs_build_version": PAIRS_BUILD_VERSION,
        "n_pairs": n_ok,
        "n_files": len(manifest),
        "sample_rate": sr,
        "bonafide_source": "GramVaani (OpenSLR 118), real Hindi telephone speech",
        "spoof_source": "edge-tts neural voices, half through an LPC vocoder",
        "construction": "paired: each spoof renders the same transcript as its bonafide",
        "channel_matched": True,
        "channel_note": ("both sides through the same codec, spoof noise floor "
                         "matched to its partner; raw pairing leaked at AUC 0.97 "
                         "on noise floor alone"),
        "items": manifest,
    }
    mpath.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    payload["manifest"] = str(mpath)
    return payload


#: Bumped when the pair build changes in a way that makes an existing set the
#: wrong set: voice selection, channel matching, filtering, anything that
#: changes the samples on disk. The runner compares this against the manifest
#: and rebuilds pairs, then the models and results, when they differ.
#:
#: BUMP THIS IN THE SAME COMMIT as any such change. A fix to match_channel
#: shipped without a bump once, and the next run read the stored audit of the
#: set built the old way and printed numbers identical to four decimals,
#: which looks exactly like a fix that did nothing.
#:
#:   1  drew from all five voices, so the three that cannot read Devanagari
#:      returned empty audio: 65 percent of renders lost, two voices left
#:   2  Devanagari voices only; conditioning moved into the front end
#:   3  channel matched on the signal the detector sees: both sides
#:      DC-removed, band-limited and trimmed first, and the quieter side
#:      lifted to the louder floor instead of only ever lifting the spoof
PAIRS_BUILD_VERSION = 3

#: Every statistic confound_audit scores. A stored audit missing any of these
#: was written by an older build and is re-derived from the audio on disk.
AUDIT_STATISTICS: Tuple[str, ...] = (
    "noise_floor_db", "snr_proxy_db", "zcr_mean", "duration",
    "quiet_centroid_hz", "quiet_tilt_db",
    # The three that were never measured and that a review found separating
    # the classes at AUC 0.98 to 1.000 on the raw pairs: bandwidth above the
    # telephone band, trailing digital silence, and DC offset.
    "band_share_hi", "band_share_lo", "trailing_quiet_s", "dc_abs",
)


def confound_audit(manifest_items: Sequence[Dict[str, Any]],
                   sr: int = TARGET_SR) -> Dict[str, Any]:
    """Can a trivial channel statistic separate bonafide from spoof?

    This runs on every build and the result is stored in the manifest, because
    the failure it guards against is silent. A spoofing set whose two classes
    differ in noise floor gives a detector an easy shortcut, and the resulting
    equal error rate looks excellent while measuring the recording conditions
    rather than the speaker. Before channel matching, the noise floor alone
    scored AUC 0.970 on this data.

    Anything above about 0.75 means the set is not usable as it stands.
    """
    import numpy as np

    from .audioio import read_audio
    from .dsp.framing import frame_signal, short_time_energy, zero_crossing_rate
    from .evaluate import roc_auc

    from .antispoof.features import BAND_HIGH_HZ, BAND_LOW_HZ, condition

    def stats_of(x: np.ndarray) -> Dict[str, float]:
        fr = frame_signal(x, 200, 80, window="hamming")
        e = short_time_energy(fr)
        db = 10.0 * np.log10(np.maximum(e, 1e-12))
        qs = _quiet_spectrum(x, sr)
        if qs is not None:
            f = np.linspace(0.0, sr / 2.0, qs.size)
            w = qs / max(float(qs.sum()), 1e-12)
            centroid = float((f * w).sum())
            lo = float(qs[f < 1000.0].mean()) if (f < 1000.0).any() else 1e-6
            hi = float(qs[f > 2500.0].mean()) if (f > 2500.0).any() else 1e-6
            tilt = float(20.0 * np.log10(max(hi, 1e-9) / max(lo, 1e-9)))
        else:
            centroid, tilt = 0.0, 0.0
        # bandwidth: share of speech-band energy outside 300 to 3400 Hz
        spec = np.abs(np.fft.rfft(x * np.hanning(x.size))) ** 2
        freqs = np.fft.rfftfreq(x.size, 1.0 / sr)
        total = float(spec.sum()) + 1e-12
        # trailing quiet: seconds after the last frame within 40 dB of peak
        loud = np.flatnonzero(db > db.max() - 40.0)
        trailing = (fr.shape[0] - 1 - int(loud[-1])) * 80 / sr if loud.size else 0.0
        return {
            "noise_floor_db": float(np.percentile(db, 10)),
            "snr_proxy_db": float(np.percentile(db, 95) - np.percentile(db, 10)),
            "zcr_mean": float(np.mean(zero_crossing_rate(fr))),
            "duration": float(x.size) / sr,
            "quiet_centroid_hz": centroid,
            "quiet_tilt_db": tilt,
            # In dB with a floor at -60, because a ratio with no floor tells
            # a real recording's exact zero from a render's one part in a
            # billion, and no detector reads below its own dither.
            "band_share_hi": max(10.0 * np.log10(float(spec[freqs >= BAND_HIGH_HZ].sum()) / total + 1e-12), -60.0),
            "band_share_lo": max(10.0 * np.log10(float(spec[freqs < BAND_LOW_HZ].sum()) / total + 1e-12), -60.0),
            "trailing_quiet_s": float(trailing),
            "dc_abs": float(abs(np.mean(x))),
        }

    rows: Dict[int, List[Dict[str, float]]] = {0: [], 1: []}
    rows_raw: Dict[int, List[Dict[str, float]]] = {0: [], 1: []}
    for it in manifest_items:
        try:
            x, _ = read_audio(it["path"], sr=sr)
        except Exception:
            continue
        if x.size < 4000:
            continue
        # The audit asks whether a trivial statistic separates the classes AS
        # THE DETECTOR SEES THEM, so the scored table is measured after the
        # same conditioning every cepstrum goes through. The raw table is
        # kept alongside: it says what the set itself carries.
        rows_raw[int(it["label"])].append(stats_of(x))
        xc = condition(x, sr)
        if xc.size < 4000:
            xc = x
        rows[int(it["label"])].append(stats_of(np.asarray(xc, dtype=np.float32)))

    out: Dict[str, Any] = {"per_statistic": {}, "n_bonafide": len(rows[0]),
                           "n_spoof": len(rows[1])}
    if not rows[0] or not rows[1]:
        out["status"] = "not enough audio to audit"
        return out

    def table(rs: Dict[int, List[Dict[str, float]]]) -> Tuple[Dict[str, Any], float]:
        per: Dict[str, Any] = {}
        worst = 0.5
        for k in AUDIT_STATISTICS:
            a = np.array([r[k] for r in rs[0]])
            b = np.array([r[k] for r in rs[1]])
            y = np.array([0] * a.size + [1] * b.size)
            auc = roc_auc(np.concatenate([a, b]), y)
            auc = max(auc, 1.0 - auc)      # leakage regardless of direction
            worst = max(worst, auc)
            per[k] = {
                "bonafide_mean": round(float(a.mean()), 4),
                "spoof_mean": round(float(b.mean()), 4),
                "auc_alone": round(float(auc), 4),
            }
        return per, worst

    out["per_statistic"], worst = table(rows)
    out["per_statistic_raw"], worst_raw = table(rows_raw)
    out["worst_auc"] = round(float(worst), 4)
    out["worst_auc_raw"] = round(float(worst_raw), 4)
    out["measured_on"] = "after telephone-band conditioning (what the detector sees)"
    out["status"] = ("channel leak, do not trust the EER" if worst > 0.75
                     else "weak residual leak" if worst > 0.62
                     else "clean")
    return out


def audit_is_current(audit: Optional[Dict[str, Any]]) -> bool:
    """Does a stored audit score every statistic this code scores?"""
    per = (audit or {}).get("per_statistic") or {}
    return all(k in per for k in AUDIT_STATISTICS)


def _pair_path(recorded: str, out_dir: Path) -> Path:
    """The clip's path on this machine, whatever machine wrote the manifest.

    The manifest stores absolute paths. A set restored from Drive into a
    clone at a different location would otherwise resolve nothing, and
    `antispoof_pairs_as_calls` would silently drop every item.
    """
    p = Path(recorded)
    if p.exists():
        return p
    return out_dir / p.parent.name / p.name


def refresh_confound_audit(out_dir: Optional[Path] = None,
                           force: bool = False) -> Dict[str, Any]:
    """Re-audit an existing pair set from its audio, without rebuilding it.

    The audit only ran inside the pair build, so a statistic added to it
    after the pairs were built could not be seen without re-rendering every
    line through the speech service, which is most of an hour. This reads
    the WAVs already on disk instead, which is seconds, and writes the new
    audit back into the manifest. Models and results are untouched: the
    audit describes the files they were trained on, it does not change them.
    """
    out_dir = Path(out_dir or (RAW_DIR / "antispoof_pairs"))
    man = load_antispoof_pairs(out_dir)
    if not man:
        return {}
    if not force and audit_is_current(man.get("confound_audit")):
        return man
    items = [dict(it, path=str(_pair_path(it["path"], out_dir)))
             for it in (man.get("items") or [])]
    audit = confound_audit(items, int(man.get("sample_rate", TARGET_SR)))
    if audit.get("worst_auc") is None:
        # the audio did not resolve; keep the old audit rather than clobber it
        return man
    audit["recomputed_from_disk"] = True
    man["confound_audit"] = audit
    (out_dir / "manifest.json").write_text(
        json.dumps(man, indent=2, ensure_ascii=False), encoding="utf-8")
    return man


def load_antispoof_pairs(out_dir: Optional[Path] = None) -> Dict[str, Any]:
    p = Path(out_dir or (RAW_DIR / "antispoof_pairs")) / "manifest.json"
    if not p.exists():
        return {}
    return json.loads(p.read_text(encoding="utf-8"))


def antispoof_pairs_as_calls(
    out_dir: Optional[Path] = None,
    split_ratio: float = 0.75,
    seed: int = 0,
) -> List[Any]:
    """The paired set wrapped as Call objects, so the scorer can train on it.

    `AntiSpoofScorer.fit` takes Calls carrying `audio_path` and `label_voice`.
    These are not conversations, they are single utterances, so the transcript
    is a placeholder and only the audio and the voice label mean anything.

    The split is speaker disjoint on the bonafide side: a spoof inherits the
    split of the real utterance whose transcript it renders, so a transcript
    never appears on both sides of the boundary. Getting that wrong would let
    the detector memorise content.
    """
    import random

    from .schema import Call, Turn

    man = load_antispoof_pairs(out_dir)
    items = man.get("items") or []
    if not items:
        return []

    speakers = sorted({it.get("speaker", "?") for it in items})
    rng = random.Random(seed)
    rng.shuffle(speakers)
    n_train = int(len(speakers) * split_ratio)
    split_of = {s: ("train" if i < n_train else "dev")
                for i, s in enumerate(speakers)}

    calls: List[Any] = []
    for i, it in enumerate(items):
        if not Path(it["path"]).exists():
            continue
        spk = it.get("speaker", f"pair_{i}")
        calls.append(Call(
            call_id=f"as_{Path(it['path']).stem}",
            turns=[Turn(index=0, speaker="caller",
                        text=(it.get("text") or "utterance")[:400])],
            label_scam=0,
            label_voice="synthetic" if int(it.get("label", 0)) == 1 else "human",
            scenario="antispoof_pair",
            speaker_id=spk,
            split=split_of.get(spk, "train"),
            audio_path=it["path"],
            sample_rate=int(man.get("sample_rate", TARGET_SR)),
            audio_source=it.get("source", "unknown"),
            meta={"kind": it.get("kind", "")},
        ))
    return calls


